// Действия игрока в кооперативе.
//
// Вынесено из Game отдельным модулем по одной причине: иначе это невозможно проверить. Раньше
// логика жила прямо в игровом цикле, вперемешку с камерой, звуком и сетью, и единственным способом
// её испытать было открыть браузер и понажимать кнопки руками. Тесты при этом дёргали внутренности
// напрямую — то есть проверяли детали, а не то, что игрок вообще может выполнить действие.
// Разница оказалась не теоретической: катапульта «работала» в таких проверках, не работая в игре.
//
// Теперь это чистая функция от (игрок, трасса, ввод). Ей всё равно, кто её вызывает — настоящая
// игра или бот в тесте, — и потому бот проверяет ровно тот код, который выполняется у игрока.
//
// Ролей здесь больше нет. Удар сверху доступен каждому: кто добежал до ударной площадки, тот и
// бьёт, а кто встал на плечо — того и подбросит. Разделение «эта кнопка не для тебя» убрано
// намеренно — оно чаще останавливало пару, чем создавало взаимодействие.

const NOOP = () => {};

export function updateRoleActions(player, course, input, yaw, { onSlam = NOOP, onCatapult = NOOP } = {}) {
  if (!player || player.downed) return;
  void yaw;

  // Удар сверху доступен только в воздухе: так он остаётся осознанным действием, а не второй
  // кнопкой прыжка.
  if (input.consume('dive') && player.startSlam()) onSlam();

  // Приземление рядом с катапультой подбрасывает того, кто стоит на плече.
  if (player.grounded && player.wasSlamming) {
    const hit = course.slamTarget(player.position);
    if (hit) onCatapult(hit);
  }
  player.wasSlamming = player.slamming;
}
