'use strict';

// Укороченная трасса для сквозных браузерных тестов — и только для них.
//
// ЗАЧЕМ. Playwright гоняет полный матч в двух настоящих Chromium на одной машине. Оба рисуют
// сцену программным WebGL, и вдвоём выдают 10–15 кадров в секунду. Физика ограничена пятью
// подшагами на кадр (MAX_SUBSTEPS), то есть кадр продвигает игру не больше чем на 83 мс: при 12
// FPS игра идёт медленнее настенных часов, и трасса из пяти сегментов перестаёт укладываться в
// бюджет теста. Это свойство раннера, а не игры — вручную та же трасса проходится за двадцать
// секунд, и боты проходят её же в тестах физики без единого промаха.
//
// Поднимать таймаут до десяти минут значило бы платить временем за то, что тест всё равно не
// проверяет: сквозной сценарий проверяет ЖИЗНЕННЫЙ ЦИКЛ матча — комнату, общий старт, сетевой
// обмен, серверный финиш, результаты, голосование, реванш, возвращение после перезагрузки, — а не
// выносливость Chromium на длинной дистанции. Проходимость всех настоящих препятствий проверяют
// боты и физика, где нет ни браузера, ни кадров.
//
// ПОЧЕМУ ЭТО НЕ ИГРОВАЯ НАСТРОЙКА. Длина гонки — правило игры, и случайно оказавшаяся на боевом
// сервере переменная не должна его менять. Поэтому одного `WOBBLE_E2E_SEGMENTS` мало: он читается
// только когда явно поднят тестовый флаг `WOBBLE_E2E=1`. Флаг ничего не значит сам по себе и
// ничего больше не включает — он существует, чтобы укорочение трассы нельзя было получить
// по одной опечатке в окружении. В deploy/wobble.env.example ни того, ни другого нет.
//
// NODE_ENV сознательно НЕ участвует: его выставляют инструменты и хостинги по своим поводам, и
// длина публичной гонки не должна зависеть от того, что кто-то счёл окружение «тестовым».
//
// Ошибка в значении здесь ПАДАЕТ, а не игнорируется молча. Оба флага бывают только в тестовом
// окружении, а тихо пропущенный override означал бы полную трассу и падение Playwright через
// двенадцать минут с сообщением «хост обязан дойти до финиша», из которого причину не видно.

const { DIFFICULTY_SEGMENTS, safeDifficulty } = require('../shared/courseSpec.js');

// Меньше двух сегментов — уже не гонка: не остаётся ни одного чекпоинта между стартом и финишем,
// а сквозной тест проверяет в том числе их прохождение.
const MIN_SEGMENTS = 2;

// Сколько сегментов должно быть в трассе сквозного теста, или null, если тестового режима нет.
// Окружение передаётся аргументом, чтобы проверять правило, не трогая process.env глобально.
function e2eSegmentCount(difficulty, env = process.env) {
  if (env.WOBBLE_E2E !== '1') return null;
  const raw = env.WOBBLE_E2E_SEGMENTS;
  if (raw === undefined || raw === '') return null;

  const requested = Number.parseInt(raw, 10);
  const natural = DIFFICULTY_SEGMENTS[safeDifficulty(difficulty)];
  if (!Number.isInteger(requested) || String(requested) !== String(raw).trim())
    throw new Error(`WOBBLE_E2E_SEGMENTS: ожидалось целое число, получено «${raw}»`);
  // Укоротить можно, удлинить — нет: длиннее собственной сложности трасса становится незнакомой
  // игрой, а тестовый флаг не для этого.
  if (requested < MIN_SEGMENTS || requested >= natural)
    throw new Error(
      `WOBBLE_E2E_SEGMENTS=${requested}: допустимо от ${MIN_SEGMENTS} до ${natural - 1} для сложности «${difficulty}»`
    );
  return requested;
}

module.exports = { e2eSegmentCount, MIN_SEGMENTS };
