// --- Разбор глав в геометрию --------------------------------------------------------------------

// Раскладывает отрезки главы в абсолютные координаты. Результат используется и клиентом для
// постройки геометрии, и сервером для проверки чекпоинтов и финиша — обе стороны видят одно и то же.
export function layoutChapter(chapter) {
  const pieces = [];
  const checkpoints = [];
  // Куда указывают уроки: идентификатор → координата вдоль трассы. Собирается здесь, чтобы
  // подсказка не съезжала при правке длин отрезков — иначе её пришлось бы поправлять руками
  // после каждого изменения главы, и рано или поздно про это забыли бы.
  const anchors = {};
  let z = START_Z;

  for (const segment of chapter.segments) {
    if (segment.kind === 'checkpoint') {
      // Арка ставится на текущей границе между отрезками и не занимает длины.
      checkpoints.push(z);
      continue;
    }
    const length = segment.length;
    const center = z - length / 2;
    // Начало отрезка, а не центр: подсказка должна успеть появиться до задачи, а не над ней.
    if (segment.id) anchors[segment.id] = { z, endZ: z - length };
    for (const prop of segment.props || []) {
      if (prop.id) anchors[prop.id] = { z: center, endZ: center };
    }
    if (segment.kind !== 'gap') {
      pieces.push({ ...segment, z: center, width: LANE_WIDTH });
    }
    z -= length;
  }

  return { pieces, checkpoints, anchors, endZ: z };
}

// Уроки с подставленными координатами. `near` превращается в точку появления, `done: { past }` —
// в отметку, которую надо пройти обоим.
export function resolveLessons(chapter, anchors) {
  // Насколько раньше показывать подсказку. Игрок должен успеть прочитать её на подходе,
  // а не обнаружить уже стоя перед провалом.
  const LEAD = 14;
  return (chapter.lessons || []).map(item => {
    const anchor = item.near ? anchors[item.near] : null;
    const done =
      item.done.past && anchors[item.done.past] ? { past: anchors[item.done.past].endZ } : item.done;
    return {
      id: item.id,
      z: item.at ?? (anchor ? anchor.z + LEAD : START_Z),
      text: item.text,
      done
    };
  });
}

const LAID_OUT = new Map();
function layoutOf(chapter) {
  let cached = LAID_OUT.get(chapter.id);
  if (!cached) {
    cached = layoutChapter(chapter);
    LAID_OUT.set(chapter.id, cached);
  }
  return cached;
}

export const COOP_CHAPTERS = CHAPTERS.map(chapter => {
  const layout = layoutOf(chapter);
  return {
    ...chapter,
    checkpoints: layout.checkpoints,
    segmentCount: layout.checkpoints.length,
    // Финишная черта — за концом последнего отрезка.
    finishZ: layout.endZ + 6
  };
});

export const COOP_CHAPTER_IDS = COOP_CHAPTERS.map(chapter => chapter.id);

export function getChapter(id) {
  return COOP_CHAPTERS.find(chapter => chapter.id === id) || COOP_CHAPTERS[0];
}

export function chapterLayout(id) {
  return layoutOf(getChapter(id));
}

// Спека в том же виде, что и у гоночной трассы: сервер работает с ними одинаково и не знает,
// проверяет он процедурную трассу или рукотворную главу.
export function coopSpec(chapterId) {
  const chapter = getChapter(chapterId);
  return {
    seed: 0,
    chapterId: chapter.id,
    difficulty: 'coop',
    title: chapter.title,
    subtitle: chapter.subtitle,
    hint: chapter.hint,
    segmentCount: chapter.segmentCount,
    checkpoints: [...chapter.checkpoints],
    lessons: resolveLessons(chapter, layoutOf(chapter).anchors),
    finishZ: chapter.finishZ,
    start: { x: 0, y: 1.2, z: START_Z - 4 },
    // Игроки стартуют рядом, но не в одной точке — иначе на старте они выталкивают друг друга.
    // Место определяется порядком входа, а не ролью: ролей больше нет.
    starts: [
      { x: -2.2, y: 1.2, z: START_Z - 4 },
      { x: 2.2, y: 1.2, z: START_Z - 4 }
    ]
  };
}

// Точка возрождения: сразу за пройденной аркой, чтобы игрок не пересекал её повторно.
// `slot` — порядковый номер игрока в комнате (0 или 1). Раньше здесь была роль; теперь роли нет,
// и место определяется просто порядком входа.
export function coopSpawnFor(spec, checkpoint = 0, slot = 0) {
  if (checkpoint <= 0) return { ...(spec.starts?.[slot] || spec.start) };
  const index = Math.min(checkpoint - 1, spec.checkpoints.length - 1);
  return { x: slot === 0 ? -2.2 : 2.2, y: 1.35, z: spec.checkpoints[index] - 3.1 };
}
