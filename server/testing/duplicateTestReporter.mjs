// Репортёр, который ловит УДВОЕНИЕ ПРОГОНА по наблюдаемому выполнению, а не по исходникам.
//
// Зачем он вместо разбора импортов. `server/testRegistry.test.mjs` ищет в тексте ссылки одного
// файла теста на другой, и четыре круга ревью подряд находили дыру именно в этом поиске: сначала он
// знал одну форму импорта из шести, потом не знал `require`. Регулярка по исходникам не может
// сделать «выполняется ровно один раз» инвариантом — путь, собранный в рантайме, или реэкспорт
// через файл, который сам не тест, она не увидит никогда.
//
// Здесь вопрос задаётся иначе: не «как записана ссылка», а «сколько раз тест ВЫПОЛНИЛСЯ». Node
// приписывает тест файлу, где тот объявлен, а не тому, кто его импортировал, поэтому удвоение видно
// как одна и та же пара «файл + имя», встреченная дважды. Каким способом её затащили — импортом,
// require, динамическим import() или собранным на ходу путём — не имеет значения.
//
// Побочно ловится обычная опечатка: два теста с одинаковым именем в одном файле. Это тоже стоит
// знать — при падении такого теста непонятно, который из двух упал.
import { relative } from 'node:path';

const DUPLICATE_MARKER = 'ТЕСТЫ ВЫПОЛНЯЛИСЬ ПО НЕСКОЛЬКУ РАЗ';

// Разделитель — нулевой символ, а не пробел. Имена тестов почти все с пробелами, и склейка через
// пробел сливала бы разные пары в одну, стоило пути и имени сойтись на границе.
const KEY_SEPARATOR = '\u0000';

export default async function* duplicateTestReporter(source) {
  const seen = new Map();

  for await (const event of source) {
    if (event.type !== 'test:pass' && event.type !== 'test:fail') continue;
    // Только верхний уровень: подтесты внутри одного набора законно повторяют имена между наборами.
    if (event.data.nesting !== 0) continue;
    const key = `${event.data.file}${KEY_SEPARATOR}${event.data.name}`;
    seen.set(key, (seen.get(key) || 0) + 1);
  }

  const duplicates = [...seen.entries()]
    .filter(([, count]) => count > 1)
    .map(([key, count]) => {
      const [file, name] = key.split(KEY_SEPARATOR);
      // Путь относительный: абсолютный шумит и меняется от машины к машине.
      return `  ${count}x ${relative(process.cwd(), file)} :: ${name}`;
    })
    .sort();

  if (!duplicates.length) return;

  yield `\n${DUPLICATE_MARKER}\n`;
  yield `${duplicates.join('\n')}\n`;
  yield '\nОдин и тот же тест выполнился несколько раз. Обычно это значит, что файл и перечислен в\n';
  yield 'package.json, и затянут другим файлом теста — импортом, require или динамически.\n';
  // Прогон обязан краснеть: иначе это заметка, а не проверка.
  process.exitCode = 1;
}

export { DUPLICATE_MARKER, KEY_SEPARATOR };
