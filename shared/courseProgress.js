// Геометрия прогресса: где именно игрок пересёк плоскость арки.
//
// Правило, по которому СЕРВЕР засчитывает арку. Им пользуются и `validateState`, и коридорная
// проверка `raceProgressSpatialGuard`, и региональная проверка кооператива — все три обязаны
// отвечать про одну и ту же точку, иначе они начинают спорить друг с другом на одном и том же
// отрезке. Ровно это и случилось: выдача чекпоинта переехала в плоскость арки, а кооперативная
// проверка региона осталась на состоянии после неё — и честная пара теряла проверку всей главы.
//
// Зачем плоскость, а не состояние после неё. Сервер видит движение выборками раз в 66 мс и реже.
// Читая рамки в конце отрезка, он читает их тем дальше от арки, чем быстрее игрок падает и чем
// хуже у него связь: при скорости падения 16 это уже метр, при одном потерянном пакете — два с
// лишним. Игрок, честно прошедший арку и сразу упавший в проём, терял её именно так. Прямая между
// двумя выборками вместо параболы — сознательное упрощение, и оно дешёвое: провес равен g·dt²/8,
// то есть 0.012 при 66 мс и 0.7 даже при полусекундном разрыве. Проверка, которую оно заменяет,
// ошибалась на всю длину падения.
//
// Модуль лежит в `shared/`, потому что описывает общую с клиентом геометрию трассы, но КЛИЕНТ ЭТИМ
// ПРАВИЛОМ НЕ ПОЛЬЗУЕТСЯ, и это осознанно.
//
// Счётчик чекпоинтов на клиенте — предсказание, а не решение; решает сервер. У предсказания есть
// обязанность, которой нет у решения: оно должно уметь ДОГНАТЬ сервер. Клиентское «я за чертой?»
// это умеет — условие остаётся истинным и на следующих кадрах, поэтому сервер, ушедший вперёд,
// рано или поздно будет догнан. Проверка пересечения этого не умеет: она срабатывает один раз, и
// клиент, отставший однажды, отстанет навсегда — а отставший клиент не пошлёт финиш вовсе.
//
// Клиент поэтому намеренно мягче сервера, а не строже. Обратный случай — клиент выдал арку, а
// сервер нет — сервер чинит сам: отказ в финише возвращает игрока к его настоящему чекпоинту (см.
// `finishRejection` в server/gameRules.js). Обратного механизма не существует, и пока его нет,
// строгий клиент опаснее мягкого.

// Ниже этой отметки арка не засчитывается: пол трассы лежит около 1, так что три единицы вниз —
// это уже под трассой, а не на ней.
export const CHECKPOINT_MIN_Y = -3;

// Внешняя рамка проёма арки — та, что была здесь и раньше. Это «игрок хотя бы над трассой», а не
// проверка опоры под ногами: самая широкая площадка трассы — стартовая с полушириной 7, сегменты
// дают от 4.5 до 6.
//
// Настоящую рамку в гонке задаёт не это число, а коридор в `raceProgressSpatialGuard`: в бою он
// обёрнут поверх `validateState` через `shadowInputPreload.js` и откатывает выдачу до
// `corridorHalfWidth + CORRIDOR_MARGIN`, то есть примерно до 6.5. Здешние 11 остаются внешней
// границей — их менять незачем, а сузить это число до коридора значило бы завести второе место,
// знающее про коридор.
export const CHECKPOINT_HALF_WIDTH = 11;

// Точка, в которой отрезок [from → to] пересекает плоскость z = line. null, если не пересекает.
//
// Прогресс идёт в минус по Z, поэтому пересечение — это `from.z >= line` и `to.z < line`. Обратный
// проход (игрока отбросило назад) пересечением не считается.
export function crossingPointAtZ(from, to, line) {
  if (!from || !to || !Number.isFinite(line)) return null;
  if (
    !Number.isFinite(from.x) ||
    !Number.isFinite(from.y) ||
    !Number.isFinite(from.z) ||
    !Number.isFinite(to.x) ||
    !Number.isFinite(to.y) ||
    !Number.isFinite(to.z)
  )
    return null;
  if (from.z < line || to.z >= line || from.z === to.z) return null;

  const ratio = (line - from.z) / (to.z - from.z);
  if (!(ratio >= 0) || ratio > 1) return null;
  return {
    x: from.x + (to.x - from.x) * ratio,
    y: from.y + (to.y - from.y) * ratio,
    z: line
  };
}

// Прошла ли точка внутри рамки арки.
export function insideCheckpointFrame(point) {
  return (
    !!point &&
    Number.isFinite(point.x) &&
    Number.isFinite(point.y) &&
    point.y > CHECKPOINT_MIN_Y &&
    Math.abs(point.x) < CHECKPOINT_HALF_WIDTH
  );
}

// Засчитана ли арка на отрезке [from → to] по внешней рамке. В гонке поверх этого работает ещё и
// коридор (см. выше); здесь его намеренно нет, чтобы про коридор знало одно место.
export function crossedCheckpoint(from, to, line) {
  return insideCheckpointFrame(crossingPointAtZ(from, to, line));
}
