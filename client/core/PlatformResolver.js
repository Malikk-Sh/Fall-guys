// Какая площадка нас запустила.
//
// От ответа зависит, какой рекламный адаптер поднимать и какие режимы показывать, поэтому ошибка
// здесь стоит дорого в обе стороны: запустить чужой SDK на своём домене или показать на площадке
// режимы, которые там не работают.
//
// Порядок определения — из `docs/MONETIZATION.md` §7.4, и первое правило в нём главное: **имя хоста
// не является признаком**. Игра живёт в iframe площадки, за её CDN и в превью-окружениях, где хост
// принадлежит кому угодно. Признаком служит файл, который кладёт сборка (`platform-config.js`), —
// он едет вместе с билдом и не зависит от того, по какому адресу его открыли.

export const PLATFORM = Object.freeze({
  WEB: 'web',
  YANDEX: 'yandex'
});

const KNOWN = new Set(Object.values(PLATFORM));

// Собственный сайт — значение по умолчанию, и это не произвол.
//
// Неизвестное значение обязано вести себя как свой домен, а не как площадка: на своём домене мы
// знаем правила и ничего чужого не запускаем. Обратная ошибка — счесть свой сайт площадкой —
// подняла бы SDK, которого там нет, и сломала бы загрузку.
export function resolvePlatform(scope = globalThis) {
  const declared = scope?.WOBBLE_PLATFORM;
  if (typeof declared === 'string' && KNOWN.has(declared)) return declared;
  return PLATFORM.WEB;
}

