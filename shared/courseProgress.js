// Единственное правило, по которому арка считается пройденной.
//
// Раньше их было два, и они не были эквивалентны.
//
// Клиент спрашивал «я ЗА чертой?» — по текущему положению, каждый шаг физики. Сервер спрашивал
// «отрезок между двумя принятыми состояниями ПЕРЕСЁК черту?» — и рамки арки проверял на состоянии,
// пришедшем ПОСЛЕ черты, раз в 66 мс. Из этой разницы росли обе живые жалобы:
//
//  1. «упал сразу после чекпоинта — точка не сохранилась». Игрок пересекает плоскость арки, падая
//     в проём. В самой плоскости он ещё выше отметки -3, а в выборке через 66 мс — уже ниже.
//     Ширина этой полосы ложного отказа равна пути падения за интервал выборки: при скорости 16
//     это больше метра, при одном потерянном пакете — больше двух. Она целиком искусственная:
//     высоту надо читать в плоскости арки, а не там, куда игрок успел улететь.
//
//  2. «пролетел сбоку от финиша — забег не закончился». Проверка пересечения может сработать
//     ТОЛЬКО ОДИН РАЗ: пересёк плоскость вне рамок — и `previous.z >= line` больше не выполнится
//     никогда. Клиент же, спрашивая «я за чертой?», засчитывал арку позже, когда игрока сносило
//     обратно к оси уже за ней. Дальше клиент считал трассу пройденной, а сервер — нет.
//
// Поэтому здесь одно правило на обе стороны: пересечение плоскости, рамки — в самой точке
// пересечения. Прямая между двумя выборками вместо параболы — сознательное упрощение, и оно
// дешёвое: провес параболы за интервал dt равен g·dt²/8, то есть 0.012 при 66 мс и 0.7 даже при
// полусекундном разрыве. Проверка, которую оно заменяет, ошибалась на всю длину падения.
//
// Ограничение «не больше одной арки за вызов» остаётся у вызывающего: на сервере оно закрывает
// способ срезать трассу одним формально допустимым состоянием после паузы.

// Ниже этой отметки арка не засчитывается ни на одной стороне: пол трассы лежит около 1, так что
// три единицы вниз — это уже под трассой, а не на ней.
export const CHECKPOINT_MIN_Y = -3;

// Полуширина проёма арки. Опоры под ней нет нигде: самая широкая площадка трассы — стартовая с
// полушириной 7, сегменты дают от 4.5 до 6, полоса кооператива — 6. Число намеренно шире геометрии:
// это рамка «игрок хотя бы над трассой», а не проверка опоры под ногами — за неё отвечает коридор
// в movementAudit.
//
// Взято серверное значение, а не клиентское. До этого их было три: сервер 11, клиент гонки 10,
// клиент кооператива 12. Одиннадцать — единственное из трёх, при котором ни один игрок не теряет
// арку, которую ему засчитывали раньше: клиент гонки становится чуть мягче (и совпадает с
// сервером), клиент кооператива — чуть строже, но обе поправки лежат в пяти единицах от края любой
// опоры, то есть над пустотой. Сузить рамку до геометрии — отдельное решение о балансе, а не часть
// починки расхождения.
export const CHECKPOINT_HALF_WIDTH = 11;

// Точка, в которой отрезок [from → to] пересекает плоскость z = line. null, если не пересекает.
//
// Прогресс идёт в минус по Z, поэтому пересечение — это `from.z >= line` и `to.z < line`. Обратный
// проход (игрока отбросило назад) пересечением не считается.
export function crossingPointAtZ(from, to, line) {
  if (!from || !to || !Number.isFinite(line)) return null;
  if (
    !Number.isFinite(from.x) ||
    !Number.isFinite(from.y) ||
    !Number.isFinite(from.z) ||
    !Number.isFinite(to.x) ||
    !Number.isFinite(to.y) ||
    !Number.isFinite(to.z)
  )
    return null;
  if (from.z < line || to.z >= line || from.z === to.z) return null;

  const ratio = (line - from.z) / (to.z - from.z);
  if (!(ratio >= 0) || ratio > 1) return null;
  return {
    x: from.x + (to.x - from.x) * ratio,
    y: from.y + (to.y - from.y) * ratio,
    z: line
  };
}

// Прошла ли точка внутри рамки арки.
export function insideCheckpointFrame(point) {
  return (
    !!point &&
    Number.isFinite(point.x) &&
    Number.isFinite(point.y) &&
    point.y > CHECKPOINT_MIN_Y &&
    Math.abs(point.x) < CHECKPOINT_HALF_WIDTH
  );
}

// Засчитана ли арка на отрезке [from → to]. Ровно эта функция вызывается и на клиенте, и на
// сервере: параметра, которым две стороны могли бы разъехаться, здесь намеренно нет.
export function crossedCheckpoint(from, to, line) {
  return insideCheckpointFrame(crossingPointAtZ(from, to, line));
}
