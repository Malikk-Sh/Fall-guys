'use strict';

// Что за забег насчитала проверка движения — в измеримом виде.
//
// Пороги в `movementAudit.js` выведены прогонами ботов: рядом с каждым стоит замеренный максимум
// честной игры. Живых людей за ними нет, и это уже стоило один раз дорого — на ботах отрыв
// траектории давал 6.947 %, на живых игроках 9.44 %. Нет причин думать, что с запасами отклонений
// будет иначе.
//
// Отсюда вопрос, на который сейчас ответить нечем: НАСКОЛЬКО БЛИЗКО честный игрок подходит к своему
// запасу. Видно только, что признак сработал — то есть что запас уже кончился. Забег, израсходовавший
// девяносто процентов, снаружи неотличим от забега, не потратившего ничего.
//
// Здесь ничего не решается и не ужесточается: счётчики уже посчитаны проверкой, эта функция только
// раскладывает их так, чтобы по ним можно было калибровать. Ни одного порога она не читает как
// правило — запас нужен ей исключительно как знаменатель.

// Доли запаса. Границы выбраны так, чтобы «сработало» отделялось само собой: признак становится
// находкой при count > budget, поэтому корзина `over` — это ровно те забеги, где он сработал, а
// остальные четыре показывают, кто насколько не дошёл.
const BUCKETS = Object.freeze(['0-25', '25-50', '50-75', '75-100', 'over']);

function bucketFor(count, budget) {
  // Запас без величины ничего не нормирует. Такого среди известных признаков нет, но полагаться на
  // это нельзя: `budgetFor` возвращает и значение по умолчанию для незнакомых имён, а незнакомое имя
  // — как раз тот случай, когда признак добавили, а запас ему назначить забыли.
  if (!Number.isFinite(budget) || budget <= 0) return count > 0 ? 'over' : '0-25';
  const share = count / budget;
  if (share > 1) return 'over';
  if (share > 0.75) return '75-100';
  if (share > 0.5) return '50-75';
  if (share > 0.25) return '25-50';
  return '0-25';
}

// Раскладка отклонений одного забега одного игрока.
//
// Признаки с нулём пропускаются намеренно. Записывать «этот признак не сработал» значило бы
// заполнить сводку строками про молчащие проверки, а вопрос стоит обратный: где расход есть и
// какой он. Сколько было забегов всего, уже известно по `finish_time`.
function anomalyMeasurements(anomalies, budgetFor) {
  if (!anomalies || typeof anomalies !== 'object') return [];
  const measurements = [];
  for (const [reason, raw] of Object.entries(anomalies)) {
    const count = Number(raw);
    if (!Number.isFinite(count) || count <= 0) continue;
    const budget = Number(budgetFor?.(reason));
    measurements.push({ reason, count, budget, bucket: bucketFor(count, budget) });
  }
  // Порядок задан именем признака, а не перебором объекта: сводка читается человеком, и одинаковые
  // забеги должны выглядеть одинаково.
  return measurements.sort((a, b) => a.reason.localeCompare(b.reason));
}

module.exports = Object.freeze({ BUCKETS, anomalyMeasurements, bucketFor });
