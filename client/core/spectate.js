// За кем смотреть, когда сам уже финишировал.
//
// Логика вынесена из Game отдельным модулем не ради красоты, а потому что это единственная часть
// досмотра, которую можно проверить без сцены, сети и браузера: на входе список бегущих, на выходе
// один идентификатор.
//
// Главное решение здесь — ПРИЛИПЧИВОСТЬ. Казалось бы, показывать надо того, кто ближе всех к
// финишу: там решается гонка. Но на длинной дистанции двое идут почти вровень и меняются местами
// по нескольку раз в секунду — камера, честно следящая за лидером, прыгала бы между ними, и
// смотреть на это невозможно. Поэтому выбранный соперник держится до конца своего забега, а замена
// ищется, только когда смотреть стало не на кого: он дошёл, вышел или потерял связь.

// Порядок «кто ближе к финишу»: сначала по числу пройденных контрольных точек, при равенстве —
// по продвижению вдоль трассы. Ось Z направлена от старта к финишу отрицательно, поэтому меньшее
// значение — дальше по трассе.
function ahead(a, b) {
  return b.checkpoint - a.checkpoint || a.z - b.z;
}

/**
 * Выбрать, за кем следить.
 *
 * @param {Array<{id: string, checkpoint: number, z: number}>} racers — те, кто ещё бежит.
 * @param {string|null} current — за кем следили в прошлом кадре.
 * @returns {string|null} идентификатор или null, если смотреть не на кого.
 */
export function spectateTarget(racers, current = null) {
  if (!racers?.length) return null;
  // Прежний соперник всё ещё на трассе — остаёмся с ним.
  if (current && racers.some(racer => racer.id === current)) return current;
  return [...racers].sort(ahead)[0].id;
}

/**
 * Кто ещё бежит: из участников убираем себя, дошедших и тех, кого не видно в кадре гонки.
 *
 * Признак «дошёл» берётся из протокола итогов, а не из снапшота: доска приходит с сервера при
 * каждом финише и перечисляет ровно тех, кто дошёл. Снапшот же — это интерполированное положение,
 * и делать по нему выводы о завершении забега значило бы гадать по картинке.
 *
 * @param {Iterable<[string, {checkpoint: number, position: {z: number}}]>} remotes
 * @param {Array<{id: string}>} board — таблица финишировавших.
 * @param {string|null} selfId
 */
export function racersStillRunning(remotes, board = [], selfId = null) {
  const finished = new Set((board || []).map(entry => entry.id));
  const racers = [];
  for (const [id, remote] of remotes) {
    if (id === selfId || finished.has(id)) continue;
    racers.push({ id, checkpoint: remote.checkpoint || 0, z: remote.position?.z ?? 0 });
  }
  return racers;
}
