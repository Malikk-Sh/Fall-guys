// Кооперативные главы, описанные данными.
//
// Почему данными, а не процедурной генерацией. Гоночные трассы генерируются из сида, и это
// правильно: там ценность в разнообразии, а любая случайная расстановка препятствий проходима.
// С кооперативными задачами так нельзя. Головоломка «один держит плиту, второй переходит»
// работает, только если пролёт нужной длины, а плиты стоят по обе стороны от него.
// Случайная расстановка либо сделает задачу нерешаемой, либо позволит пройти её в одиночку —
// и то и другое убивает смысл кооператива.
//
// Модуль общий с сервером: сервер по нему выводит чекпоинты и проверяет финиш, не строя геометрию.
//
// ---
//
// Формат: глава — это последовательность отрезков вдоль оси Z, а не список координат.
//
// Так сделано намеренно. При ручной расстановке координат легко получить отрезок, наложенный на
// соседний, или пропасть, которой на деле нет, потому что её перекрывает пол. Ошибка при этом
// молчаливая: уровень строится, выглядит правдоподобно, но головоломка проходится в обход. Когда
// геометрия набирается отрезками подряд, такие ошибки невозможны по построению.
//
// Ключевой приём: в игре нет боковых столкновений — сквозь стену игрок просто пройдёт. Поэтому
// преграда здесь не стена, а ОТСУТСТВИЕ ПОЛА. «Ворота» — это выдвижной пролёт над пропастью:
// закрыты — провала не перейти, открыты — пролёт появился. Такую преграду нельзя обойти сбоку и
// нельзя проскочить рывком, и работает она на той физике, что уже есть.
//
// Правило проектирования: в каждой главе есть участок, который физически невозможно пройти одному.
// Не «вдвоём быстрее», а «одному никак».
//
// ---
//
// Ролей больше нет: персонажи одинаковые. Кооператив держится не на разных способностях, а на
// присутствии — плиту надо КОМУ-ТО держать, пока другой идёт. Кто держит, а кто идёт, игроки
// решают сами и меняются в любой момент. Подробнее о причинах — в shared/protocol.js.

// Ширина дорожки. Общая для всех глав: габариты должны считываться с первого взгляда.
export const LANE_WIDTH = 12;

// Пропасть шире этого прыжком не берётся. Всё, что должно требовать напарника, делаем не короче.
export const UNJUMPABLE_GAP = 12;

// Насколько широкую пропасть можно ставить «на перепрыгнуть самому».
//
// Измерено ботами, а не взято на глаз: прыжок с разбега покрывает около 5.3 единицы, с удержанием
// кнопки в воздухе (планированием) — заметно больше. Запас в треть нужен, чтобы прыжок получался,
// а не требовал попадания в кадр; тест меряет дальность сам и уронит сборку, если правка физики
// сделает эти пропасти непроходимыми.
export const JUMPABLE_GAP = 3.5;

// Первый отрезок начинается здесь; дальше уровень уходит в минус по Z, как и гоночные трассы.
const START_Z = 14;

// --- Конструкторы отрезков -------------------------------------------------------------------

// Обычный пол. props — предметы и опасности на нём.
const floor = (length, props = []) => ({ kind: 'floor', length, props });

// Пропасть. Идентификатор нужен, только если на пропасть ссылается урок.
const gap = (length, id = null) => ({ kind: 'gap', length, id });

// Выдвижной пролёт над пропастью, управляемый плитами.
//
// Мост существует ровно столько, сколько на какой-нибудь из его плит кто-то СТОИТ. Никакой
// фиксации: сошёл с плиты — моста нет. Поэтому плиты обязаны стоять по ОБЕ стороны пропасти, и
// решение всегда одно и то же:
//
//   1. первый встаёт на плиту перед пропастью — мост появляется;
//   2. второй переходит;
//   3. первый сходит с плиты — мост исчезает, но второй уже на той стороне;
//   4. второй встаёт на плиту за пропастью — мост появляется снова;
//   5. первый переходит.
//
// Раньше дальняя плита «закрепляла» мост насовсем. Так было проще проходить, но хуже играть:
// мост оставался стоять, и вторая половина головоломки исчезала — напарник переставал быть
// нужен. Теперь нужен всё время.
//
// `requires` — все плиты этих ворот, с обеих сторон. Тест следит, чтобы плита была и до пропасти,
// и после: без дальней плиты первый останется на своей стороне навсегда.
const gateSpan = (id, length, requires) => ({
  kind: 'gateSpan',
  id,
  length,
  requires
});

// Ворота синхронности: пролёт появляется, если оба пересекли черту почти одновременно, и после
// этого остаётся. Одновременность доказана — заставлять пробегать быстрее таймера незачем.
const syncSpan = (id, length, windowMs = 900) => ({ kind: 'syncSpan', id, length, windowMs });

// Качающаяся платформа над пропастью: проходится обычным прыжком, но требует расчёта.
const movingSpan = (length, { range = 4, speed = 0.7 } = {}) => ({
  kind: 'movingSpan',
  length,
  range,
  speed
});

// Осыпающиеся плитки: пол, который исчезает через мгновение после того, как на него наступили.
//
// Мягкая опасность из трёх ступеней документа: сама по себе не убивает, но не даёт стоять и
// заставляет двигаться. В кооперативе получается интереснее, чем в одиночку: второй бежит по уже
// подломленным плиткам и должен выбирать другой ряд.
const collapsing = (id, length, { delay = 0.55, respawn = 3.2, lanes = 3 } = {}) => ({
  kind: 'collapsing',
  id,
  length,
  delay,
  respawn,
  lanes
});

const checkpoint = () => ({ kind: 'checkpoint' });

// --- Предметы и опасности на полу --------------------------------------------------------------

// Плита. Нажимается кем угодно: ролей нет, важно только что кто-то на ней стоит.
const plate = (id, x) => ({ type: 'plate', id, x });

// Катапульта: один бьёт ударом сверху, стоящего на длинном плече подбрасывает. Бить и стоять
// может кто угодно — кто первым добежал до какой стороны.
//
// `forward` — какая доля силы уходит вперёд, а не вверх. Дальность полёта складывается из импульса,
// гравитации и управления в воздухе, по числам её не видно, поэтому тест меряет её симуляцией и
// проверяет, что катапульта действительно перебрасывает через свою пропасть.
const catapult = (id, x, power = 26, forward = 0.7) => ({
  type: 'catapult',
  id,
  x,
  power,
  forward
});

// Конвейер: пол под ним едет. Мягкая опасность — сам не убивает, но сносит к тому, что убивает.
// Отрицательная сила тянет назад, положительная — вперёд.
const conveyor = force => ({ type: 'conveyor', force });

// Вентилятор: сдувает вбок.
//
// `force` — скорость сноса в единицах в секунду на пике порыва. Сравнивать её надо с бегом
// (7.7 ед/с): 4 — заметный крен, 6 — против ветра остаётся только ползти, и надо ждать затишья.
// Раньше сила прибавлялась к скорости и почти целиком съедалась торможением управления —
// на пике набегало меньше половины единицы в секунду, то есть ничего.
//
// Выше примерно 6 ставить бессмысленно: снос ограничен долей беговой скорости (WIND_MAX в
// CoopCourse.js), иначе игрока несло бы назад. Попутный ветер вдобавок ослаблен — при равном
// вкладе порыв в спину разгонял вдвое, и участок проходился по удаче, а не по расчёту.
//
// `period` — длительность полного цикла «затишье → порыв». Ветер не дует ровно: он даёт окно,
// в которое надо успеть. Это тот же приём, что и три такта пресса, только для мягкой опасности —
// препятствие не убивает, но требует выбрать момент.
const fan = (force, { period = 4.2, x = 0 } = {}) => ({ type: 'fan', force, period, x });

// Маятник: качающийся молот. Жёсткая опасность — не убивает, но отбрасывает, и рядом с краем
// этого достаточно.
const pendulum = (id, x, { range = 5, speed = 1.1, knock = 14 } = {}) => ({
  type: 'pendulum',
  id,
  x,
  range,
  speed,
  knock
});

// Пресс: смертельная опасность, отправляет на чекпоинт. Работает в три такта, как и требует
// документ, и это не украшение — внезапная смерть воспринимается как несправедливость, а не как
// ошибка игрока:
//
//   1. предупреждение — плита светится и гудит, `warn` секунд;
//   2. удар — `strike` секунд внизу, вот здесь и убивает;
//   3. подъём — окно, в которое надо проскочить.
const crusher = (id, x, { period = 3.4, warn = 0.9, strike = 0.7, width = 5 } = {}) => ({
  type: 'crusher',
  id,
  x,
  period,
  warn,
  strike,
  width
});

// --- Обучение --------------------------------------------------------------------------------
//
// Механики не следуют из вида уровня: что плиту надо КОМУ-ТО держать, пока другой идёт, из
// геометрии не прочитать. Это надо сказать, и сказать вовремя — карточка на старте исчезает
// задолго до задачи, про которую в ней написано.
//
// Поэтому урок — это данные рядом с той механикой, о которой он рассказывает:
//
//   `near` — к чему урок привязан: идентификатор пролёта или плиты. Точка появления берётся из
//            разметки главы, а не пишется руками, иначе подсказка съезжала бы при любой правке длин.
//   `text` — что показать. Ролей нет, поэтому текст один на обоих: задача у них общая.
//   `done` — когда урок усвоен. Условие выводится из того же состояния, что и сами механики,
//            поэтому обучение не требует ни одного сетевого сообщения.
//
// Условия `done`: { span: id } — пролёт выдвинут; { plates: [id…] } — все плиты нажаты;
// { past: id } — оба прошли отметку.
const lesson = (id, { near = null, at = null, text, done }) => ({ id, near, at, text, done });

